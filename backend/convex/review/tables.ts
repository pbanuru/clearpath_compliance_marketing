import { quickContext, quickRule, quickNote, quickStatus } from './quickCheckTypes';
import { defineTable } from 'convex/server';
import { v } from 'convex/values';
import {
  analysis,
  analysisStatus,
  channel,
  confidence,
  eventType,
  findingCounts,
  findingStatus,
  location,
  operation,
  outcome,
  product,
  provider,
  responses,
  reviewStatus,
  severity,
  span,
} from './types';
import { extractionKind, storedVideoEvent } from './videoTypes';

export const reviewTables = {
  quickChecks: defineTable({
    owner: v.string(),
    contextHash: v.string(),
    context: quickContext,
    status: quickStatus,
    rules: v.array(quickRule),
    notes: v.array(quickNote),
    startedAt: v.number(),
    finishedAt: v.optional(v.number()),
    error: v.optional(v.string()),
    runKey: v.string(),
  }).index('by_owner_and_contextHash', ['owner', 'contextHash']),
  reviewCosts: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    knownUsd: v.number(),
    unknownCalls: v.number(),
    spans: v.number(),
  }).index('by_reviewId', ['reviewId']),
  reviews: defineTable({
    owner: v.string(),
    campaignId: v.optional(v.id('campaigns')),
    title: v.string(),
    product,
    channel,
    jurisdictions: v.array(v.string()),
    offerTerms: v.optional(v.string()),
    goLiveDate: v.optional(v.string()),
    pinnedRank: v.optional(v.number()),
    pinnedSort: v.optional(v.union(v.literal('go_live'), v.literal('waiting'))),
    ruleChangeRecheck: v.optional(v.boolean()),
    notes: v.optional(v.string()),
    status: reviewStatus,
    currentVersion: v.number(),
    example: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
    waitingSince: v.number(),
    coverAssetId: v.id('assets'),
    counts: findingCounts,
    queueBucket: v.string(),
    resubmissionRank: v.number(),
    usage: v.optional(v.union(v.literal('unknown'), v.literal('live'), v.literal('retired'))),
    wasApproved: v.optional(v.boolean()),
    recheckOpen: v.optional(v.boolean()),
    recheckFailed: v.optional(v.boolean()),
    pendingRechecks: v.optional(v.number()),
    recheck: v.optional(
      v.object({
        key: v.string(),
        fromVersion: v.number(),
        toVersion: v.number(),
        title: v.string(),
        changeSummary: v.string(),
        changedAt: v.optional(v.number()),
        approvedAt: v.optional(v.number()),
        oldCheck: v.optional(v.string()),
        newCheck: v.optional(v.string()),
        newFindings: v.optional(v.number()),
        materialVersion: v.optional(v.number()),
        sourceLabel: v.optional(v.string()),
      }),
    ),
  })
    .index('by_owner_and_wasApproved_and_updatedAt', ['owner', 'wasApproved', 'updatedAt'])
    .index('by_owner_and_recheckOpen_and_updatedAt', ['owner', 'recheckOpen', 'updatedAt'])
    .index('by_owner_and_status_and_updatedAt', ['owner', 'status', 'updatedAt'])
    .index('by_owner_and_updatedAt', ['owner', 'updatedAt'])
    .index('by_owner_and_campaignId_and_updatedAt', ['owner', 'campaignId', 'updatedAt'])
    .index('by_owner_and_queueBucket_and_resubmissionRank_and_waitingSince', [
      'owner',
      'queueBucket',
      'resubmissionRank',
      'waitingSince',
    ]),
  reviewVersions: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    number: v.number(),
    assetIds: v.array(v.id('assets')),
    submitterNote: v.optional(v.string()),
    responses,
    createdAt: v.number(),
    analysis,
    policyVersions: v.optional(v.array(v.object({ key: v.string(), version: v.number() }))),
    quickCheckId: v.optional(v.id('quickChecks')),
  }).index('by_reviewId_and_number', ['reviewId', 'number']),
  findings: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    version: v.number(),
    source: v.union(v.literal('ai'), v.literal('reviewer'), v.literal('recheck')),
    severity,
    policyId: v.string(),
    policyVersion: v.optional(v.number()),
    title: v.string(),
    explanation: v.string(),
    suggestedFix: v.optional(v.string()),
    location: v.optional(location),
    quoteFound: v.optional(v.boolean()),
    confidence: v.optional(confidence),
    status: findingStatus,
    dismissReason: v.optional(v.string()),
    recheckNote: v.optional(v.string()),
    previousFindingId: v.optional(v.id('findings')),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index('by_reviewId_and_version', ['reviewId', 'version']),
  decisions: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    version: v.number(),
    outcome,
    note: v.optional(v.string()),
    acceptedFindingIds: v.array(v.id('findings')),
    decidedAt: v.number(),
    policyVersions: v.optional(v.array(v.object({ key: v.string(), version: v.number() }))),
    decidedBy: v.optional(v.string()),
    dismissedCount: v.optional(v.number()),
  }).index('by_reviewId_and_version', ['reviewId', 'version']),
  reviewEvents: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    type: eventType,
    version: v.number(),
    findingId: v.optional(v.id('findings')),
    detail: v.optional(v.string()),
    at: v.number(),
  })
    .index('by_reviewId_and_at', ['reviewId', 'at'])
    .index('by_findingId_and_type_and_at', ['findingId', 'type', 'at']),
  assetExtractions: defineTable({
    owner: v.string(),
    assetId: v.id('assets'),
    kind: extractionKind,
    status: analysisStatus,
    segments: v.array(v.object({ start: v.number(), end: v.number(), text: v.string() })),
    words: v.optional(v.array(v.object({ start: v.number(), end: v.number(), text: v.string() }))),
    timeline: v.optional(v.array(storedVideoEvent)),
    spans: v.optional(v.array(span)),
    runKey: v.optional(v.string()),
    wordsTruncated: v.optional(v.boolean()),
    segmentsTruncated: v.optional(v.boolean()),
    totalSegments: v.optional(v.number()),
    durationSeconds: v.optional(v.number()),
    model: v.string(),
    error: v.optional(v.string()),
    createdAt: v.number(),
  }).index('by_assetId_and_kind', ['assetId', 'kind']),
  aiSpans: defineTable({
    owner: v.string(),
    reviewId: v.optional(v.id('reviews')),
    assetId: v.optional(v.id('assets')),
    version: v.optional(v.number()),
    quickCheckId: v.optional(v.id('quickChecks')),
    runKey: v.string(),
    ...span.fields,
  })
    .index('by_reviewId_and_version', ['reviewId', 'version'])
    .index('by_runKey', ['runKey'])
    .index('by_assetId', ['assetId']),
  aiUsageDaily: defineTable({
    owner: v.string(),
    day: v.string(),
    provider,
    model: v.string(),
    operation,
    calls: v.number(),
    failedCalls: v.number(),
    knownCostUsd: v.number(),
    unknownCostCalls: v.number(),
  }).index('by_owner_and_day_and_provider_and_model_and_operation', [
    'owner',
    'day',
    'provider',
    'model',
    'operation',
  ]),
  reviewCounts: defineTable({
    rechecks: v.optional(v.number()),
    approvedHistory: v.optional(v.number()),
    owner: v.string(),
    needs_review: v.number(),
    changes_requested: v.number(),
    approved: v.number(),
    all: v.number(),
  }).index('by_owner', ['owner']),
};
