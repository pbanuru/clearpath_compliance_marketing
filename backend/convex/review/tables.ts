import { defineTable } from 'convex/server';
import { v } from 'convex/values';
import {
  analysis,
  analysisStatus,
  channel,
  confidence,
  eventType,
  findingCounts,
  findingStatus,
  location,
  operation,
  outcome,
  product,
  responses,
  reviewStatus,
  severity,
  span,
} from './types';

export const reviewTables = {
  reviewCosts: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    knownUsd: v.number(),
    unknownCalls: v.number(),
    spans: v.number(),
  }).index('by_reviewId', ['reviewId']),
  reviews: defineTable({
    owner: v.string(),
    title: v.string(),
    product,
    channel,
    jurisdictions: v.array(v.string()),
    offerTerms: v.optional(v.string()),
    goLiveDate: v.optional(v.string()),
    notes: v.optional(v.string()),
    status: reviewStatus,
    currentVersion: v.number(),
    example: v.optional(v.string()),
    createdAt: v.number(),
    updatedAt: v.number(),
    waitingSince: v.number(),
    coverAssetId: v.id('assets'),
    counts: findingCounts,
    queueBucket: v.string(),
    resubmissionRank: v.number(),
    usage: v.optional(v.union(v.literal('unknown'), v.literal('live'), v.literal('retired'))),
    recheckFailed: v.optional(v.boolean()),
    pendingRechecks: v.optional(v.number()),
    recheck: v.optional(
      v.object({
        key: v.string(),
        fromVersion: v.number(),
        toVersion: v.number(),
        title: v.string(),
        changeSummary: v.string(),
      }),
    ),
  })
    .index('by_owner_and_status_and_updatedAt', ['owner', 'status', 'updatedAt'])
    .index('by_owner_and_updatedAt', ['owner', 'updatedAt'])
    .index('by_owner_and_queueBucket_and_resubmissionRank_and_waitingSince', [
      'owner',
      'queueBucket',
      'resubmissionRank',
      'waitingSince',
    ]),
  reviewVersions: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    number: v.number(),
    assetIds: v.array(v.id('assets')),
    submitterNote: v.optional(v.string()),
    responses,
    createdAt: v.number(),
    analysis,
    policyVersions: v.optional(v.array(v.object({ key: v.string(), version: v.number() }))),
  }).index('by_reviewId_and_number', ['reviewId', 'number']),
  findings: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    version: v.number(),
    source: v.union(v.literal('ai'), v.literal('reviewer'), v.literal('recheck')),
    severity,
    policyId: v.string(),
    policyVersion: v.optional(v.number()),
    title: v.string(),
    explanation: v.string(),
    suggestedFix: v.optional(v.string()),
    location: v.optional(location),
    quoteFound: v.optional(v.boolean()),
    confidence: v.optional(confidence),
    status: findingStatus,
    dismissReason: v.optional(v.string()),
    recheckNote: v.optional(v.string()),
    previousFindingId: v.optional(v.id('findings')),
    createdAt: v.number(),
    updatedAt: v.number(),
  }).index('by_reviewId_and_version', ['reviewId', 'version']),
  decisions: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    version: v.number(),
    outcome,
    note: v.optional(v.string()),
    acceptedFindingIds: v.array(v.id('findings')),
    decidedAt: v.number(),
    policyVersions: v.optional(v.array(v.object({ key: v.string(), version: v.number() }))),
  }).index('by_reviewId_and_version', ['reviewId', 'version']),
  reviewEvents: defineTable({
    owner: v.string(),
    reviewId: v.id('reviews'),
    type: eventType,
    version: v.number(),
    findingId: v.optional(v.id('findings')),
    detail: v.optional(v.string()),
    at: v.number(),
  }).index('by_reviewId_and_at', ['reviewId', 'at']),
  assetExtractions: defineTable({
    owner: v.string(),
    assetId: v.id('assets'),
    kind: v.literal('transcript'),
    status: analysisStatus,
    segments: v.array(v.object({ start: v.number(), end: v.number(), text: v.string() })),
    model: v.string(),
    error: v.optional(v.string()),
    createdAt: v.number(),
  }).index('by_assetId_and_kind', ['assetId', 'kind']),
  aiSpans: defineTable({
    owner: v.string(),
    reviewId: v.optional(v.id('reviews')),
    version: v.optional(v.number()),
    runKey: v.string(),
    ...span.fields,
  })
    .index('by_reviewId_and_version', ['reviewId', 'version'])
    .index('by_runKey', ['runKey']),
  aiUsageDaily: defineTable({
    owner: v.string(),
    day: v.string(),
    provider: v.literal('openai'),
    model: v.string(),
    operation,
    calls: v.number(),
    failedCalls: v.number(),
    knownCostUsd: v.number(),
    unknownCostCalls: v.number(),
  }).index('by_owner_and_day_and_provider_and_model_and_operation', [
    'owner',
    'day',
    'provider',
    'model',
    'operation',
  ]),
  reviewCounts: defineTable({
    owner: v.string(),
    needs_review: v.number(),
    changes_requested: v.number(),
    approved: v.number(),
    all: v.number(),
  }).index('by_owner', ['owner']),
};
